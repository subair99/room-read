import { LIMIT_NOTE } from "../evidence/labels";
import type { CheckResult } from "../types";

const VERDICT_TEXT = { ship: "Ship it", tweak: "Tweak", rework: "Rework" } as const;
const BAND_COLOR = { green: "#1a7f37", amber: "#b26b00", red: "#c62828", unknown: "#6b7280" } as const;

/**
 * One-page room brief as printable HTML. The browser's "Save as PDF" turns it
 * into the PDF deliverable without adding a headless-browser dependency.
 */
export function renderBriefHtml(script: string, result: CheckResult, title = "Room brief"): string {
  const verdict = result.verdict === "tweak" ? `Tweak ${result.tweakCount} line(s)` : VERDICT_TEXT[result.verdict];
  const rows = result.verdicts
    .map(
      (v) => `<tr><td>${esc(v.reference.text)}</td><td style="color:${BAND_COLOR[v.band]};font-weight:600">${v.band}</td><td>${esc(v.reason)}</td></tr>`,
    )
    .join("");
  return `<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)}</title>
<style>
body{font:14px/1.5 system-ui,sans-serif;max-width:760px;margin:32px auto;padding:0 16px;color:#111}
h1{font-size:22px;margin:0 0 4px}.muted{color:#555}table{width:100%;border-collapse:collapse;margin:16px 0}
td,th{border-bottom:1px solid #ddd;padding:6px 8px;text-align:left;vertical-align:top}
pre{white-space:pre-wrap;background:#f6f6f6;padding:12px;border-radius:8px}
@media print{body{margin:0}}
</style></head><body>
<h1>${esc(title)}</h1>
<p class="muted">Audience: ${result.audiences.map((a) => esc(a.label)).join(" + ")} · Verdict: <strong>${verdict}</strong></p>
<pre>${esc(script)}</pre>
<table><thead><tr><th>Reference</th><th>Band</th><th>Why (from Qloo ranks)</th></tr></thead><tbody>${rows}</tbody></table>
<p class="muted">${esc(LIMIT_NOTE)}</p>
<p class="muted">Generated by RoomRead · ${new Date().toISOString().slice(0, 10)} · ${result.receipts.filter((r) => r.source === "qloo").length} Qloo calls logged</p>
<script>window.onload=()=>window.print()</script>
</body></html>`;
}

function esc(s: string): string {
  return s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);
}
